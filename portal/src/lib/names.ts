export function feminine(surname: string): string {
  if (/(ов|ев|ёв|ин|ын)$/.test(surname)) return surname + "а";
  if (surname.endsWith("ский")) return surname.slice(0, -4) + "ская";
  return surname;
}

export function patronymic(father: string, male: boolean): string {
  const stems: Record<string, [string, string]> = {
    Сергей: ["Сергеевич", "Сергеевна"], Андрей: ["Андреевич", "Андреевна"], Алексей: ["Алексеевич", "Алексеевна"],
    Дмитрий: ["Дмитриевич", "Дмитриевна"], Игорь: ["Игоревич", "Игоревна"], Олег: ["Олегович", "Олеговна"],
    Владимир: ["Владимирович", "Владимировна"], Николай: ["Николаевич", "Николаевна"], Евгений: ["Евгеньевич", "Евгеньевна"],
    Павел: ["Павлович", "Павловна"], Виктор: ["Викторович", "Викторовна"], Юрий: ["Юрьевич", "Юрьевна"],
  };
  return stems[father][male ? 0 : 1];
}

const TRANSLIT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i", й: "y", к: "k", л: "l", м: "m", н: "n",
  о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "",
  э: "e", ю: "yu", я: "ya",
};
export const translit = (s: string) =>
  s.toLowerCase().split("").map((c) => TRANSLIT[c] ?? (/[a-z0-9]/.test(c) ? c : "")).join("");
